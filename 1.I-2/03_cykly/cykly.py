a = 0
while a <= 100:  # cyklus while - kontroluje podmínku, dokud platí, opakuje se
    print(a)  # jakmile podmínka přestane platit, cyklus skončí
    a += 1

# vypsat sudá čísla
a = 0
while a <= 100:
    print(a)
    a += 2

# vypsat čísla od 100 do 0 - pozpátku
a = 100
while a >= 0:
    print(a)
    a -= 1
